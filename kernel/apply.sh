#!/bin/bash
# Apply the Pixelbook kernel changes to an AOSP kernel/common tree
# (tag android17-6.18-2026-06_r52, commit 3938c8d97142). Idempotent.
#   kernel/apply.sh /path/to/kernel/common
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
K="${1:?usage: apply.sh <kernel tree>}"

cp "$HERE/isa_emu.c" "$K/arch/x86/kernel/isa_emu.c"
cp "$HERE/../isa_emu/isa_emu_core.h" "$K/arch/x86/kernel/isa_emu_core.h"
cp "$HERE/../isa_emu/isa_emu_fastpath.h" "$K/arch/x86/kernel/isa_emu_fastpath.h"
cp "$HERE/../isa_emu/isa_emu_fastpath_table.h" "$K/arch/x86/kernel/isa_emu_fastpath_table.h"

python3 - "$K" <<'PY'
import sys, pathlib
K = pathlib.Path(sys.argv[1])

def edit(rel, marker, old, new):
    p = K / rel
    s = p.read_text()
    if marker in s:
        return
    if old not in s:
        sys.exit(f"apply.sh: anchor not found in {rel}")
    p.write_text(s.replace(old, new, 1))
    print("patched", rel)

edit("arch/x86/kernel/Makefile", "isa_emu.o",
     "obj-$(CONFIG_X86_UMIP)\t\t\t+= umip.o\n",
     "obj-$(CONFIG_X86_UMIP)\t\t\t+= umip.o\nobj-$(CONFIG_X86_ISA_EMU)\t\t+= isa_emu.o\n")

edit("arch/x86/Kconfig", "config X86_ISA_EMU",
     "config X86_UMIP\n",
     """config X86_ISA_EMU
	bool "Emulate GFNI/AVX-VNNI/VAES/VPCLMULQDQ/SHA-NI for user space"
	depends on X86_64
	default y
	help
	  Emulate, in the user-mode invalid-opcode handler, a small set of
	  vector instructions that some prebuilt user space assumes without
	  checking CPUID but that pre-Ice-Lake AVX2 CPUs do not implement.
	  Each emulated instruction costs a trap, so this is a compatibility
	  aid, not a performance feature. See arch/x86/kernel/isa_emu.c.

config X86_UMIP
""")

edit("arch/x86/include/asm/traps.h", "isa_emu_fixup",
     "#endif /* _ASM_X86_TRAPS_H */",
     """#ifdef CONFIG_X86_ISA_EMU
bool isa_emu_fixup(struct pt_regs *regs);
#else
static inline bool isa_emu_fixup(struct pt_regs *regs) { return false; }
#endif

#endif /* _ASM_X86_TRAPS_H */""")

# Google's prebuilt GKI modules (system_dlkm) are signed with the key generated by
# Google's kernel build. A rebuilt kernel cannot verify that signature, so they load as
# "unsigned" and the GKI protected-symbol checks would reject them.
edit("kernel/module/Kconfig", "config MODULE_SIG_PROTECT_PREBUILT",
     """config MODULE_SIG_PROTECT
""",
     """config MODULE_SIG_PROTECT_PREBUILT
	bool "Let modules with unverifiable signatures use protected symbols"
	depends on MODULE_SIG_PROTECT
	default y
	help
	  Allow prebuilt GKI modules, whose signing key this rebuilt kernel does
	  not have, to use and export protected symbols. Only for running an
	  unmodified vendor/system module set on a rebuilt GKI kernel.

config MODULE_SIG_PROTECT
""")

edit("kernel/module/main.c", "MODULE_SIG_PROTECT_PREBUILT",
     """	if (fsa.is_protected && !mod->sig_ok) {
""",
     """	if (fsa.is_protected && !mod->sig_ok &&
	    !IS_ENABLED(CONFIG_MODULE_SIG_PROTECT_PREBUILT)) {
""")

edit("kernel/module/main.c", "CONFIG_MODULE_SIG_PROTECT_PREBUILT) && is_protected_export",
     """		if (!mod->sig_ok && is_protected_export(s)) {
""",
     """		if (!mod->sig_ok && !IS_ENABLED(CONFIG_MODULE_SIG_PROTECT_PREBUILT) && is_protected_export(s)) {
""")

# The Pixelbook touchpad (Google "Rose", 18d1:5028) sends a hover-only first report for every new touch: tip
# switch off, position always the centre of the pad, ~100 ms before the real position arrives. MT_CLS_GOOGLE
# keeps such hovering contacts alive (ABS_MT_DISTANCE=1), which ChromeOS userspace knows to ignore but
# Android's touchpad stack treats as a finger down at the centre, so every new touch makes the pointer jump.
# Without the hover quirk those reports are dropped and only real touches reach user space.
edit("drivers/hid/hid-multitouch.c", "pixelbook: no hover",
     """	{ .name = MT_CLS_GOOGLE,
		.quirks = MT_QUIRK_ALWAYS_VALID |
			MT_QUIRK_CONTACT_CNT_ACCURATE |
			MT_QUIRK_SLOT_IS_CONTACTID |
			MT_QUIRK_HOVERING
	},""",
     """	{ .name = MT_CLS_GOOGLE,	/* pixelbook: no hover (see kernel/apply.sh) */
		.quirks = MT_QUIRK_ALWAYS_VALID |
			MT_QUIRK_CONTACT_CNT_ACCURATE |
			MT_QUIRK_SLOT_IS_CONTACTID
	},""")

# AVS (Skylake/Kaby Lake audio DSP): avs_path_set_constraint() sizes its rate/channel/sample-bits arrays by the
# number of paths in the template but stores one entry per I2S/DMIC copier module, and the Pixelbook speaker path
# (ChromeOS's max98927 topology) has more of those than paths. Google builds snd-soc-avs.ko with UBSAN bounds traps,
# so opening the speaker PCM hit "UBSAN: ... avs_path_set_constraint+0x36d" and an Oops that took the machine down
# (usb-dump11-audio, ramoops). Size the arrays by the number of modules instead: an upper bound of what is stored.
# snd-soc-avs is not built into the kernel; kernel/build_avs_module.sh builds the fixed module.
edit("sound/soc/intel/avs/path.c", "pixelbook: one slot per module",
     """	i = 0;
	list_for_each_entry(path_template, &template->path_list, node)
		i++;

	rlist = kcalloc(i, sizeof(*rlist), GFP_KERNEL);""",
     """	i = 0;	/* pixelbook: one slot per module, not per path (see kernel/apply.sh) */
	list_for_each_entry(path_template, &template->path_list, node) {
		struct avs_tplg_pipeline *pipeline_template;

		list_for_each_entry(pipeline_template, &path_template->ppl_list, node) {
			struct avs_tplg_module *module_template;

			list_for_each_entry(module_template, &pipeline_template->mod_list, node)
				i++;
		}
	}

	rlist = kcalloc(i, sizeof(*rlist), GFP_KERNEL);""")

edit("arch/x86/kernel/traps.c", "isa_emu_fixup",
     """{
	do_error_trap(regs, 0, "invalid opcode", X86_TRAP_UD, SIGILL,
""",
     """{
	/* Emulate ISA extensions user space assumes but this CPU lacks. */
	if (user_mode(regs) && isa_emu_fixup(regs))
		return;

	do_error_trap(regs, 0, "invalid opcode", X86_TRAP_UD, SIGILL,
""")
PY
echo "applied to $K"
