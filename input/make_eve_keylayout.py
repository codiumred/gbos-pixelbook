#!/usr/bin/env python3
"""Derive the Pixelbook keyboard layout from the image's own Generic.kl.

  make_eve_keylayout.py <Generic.kl> <output .kl>

The Pixelbook's EC keyboard reports its top row as plain F1-F10 (verified with a key trace on the device:
Esc, F1..F10, F13, plus a separate power button), where ChromeOS maps them in user space. Android picks the
layout by device name (AT_Translated_Set_2_keyboard.kl), so a layout that gives those scan codes the
meaning printed on the keys is all that is needed; every other key stays as in Generic.kl.

  F1 Back   F2 Refresh   F3 Full screen   F4 Overview   F5 Brightness down   F6 Brightness up
  F7 Play/pause   F8 Mute   F9 Volume down   F10 Volume up

Fails if Generic.kl no longer has the expected lines, so an incompatible future image is noticed at build time.
"""
import re, sys

TOP_ROW = {  # Linux key code: (old Android name, new Android name)
    59: ("F1", "BACK"),
    60: ("F2", "REFRESH"),
    61: ("F3", "FULLSCREEN"),
    62: ("F4", "RECENT_APPS"),
    63: ("F5", "BRIGHTNESS_DOWN"),
    64: ("F6", "BRIGHTNESS_UP"),
    65: ("F7", "MEDIA_PLAY_PAUSE"),
    66: ("F8", "VOLUME_MUTE"),
    67: ("F9", "VOLUME_DOWN"),
    68: ("F10", "VOLUME_UP"),
}


def main():
    src, dst = sys.argv[1], sys.argv[2]
    text = open(src, encoding="utf-8").read()
    names = set(re.findall(r"^key\s+\d+\s+(\w+)", text, re.M))
    for code, (old, new) in TOP_ROW.items():
        pattern = re.compile(rf"^(key\s+{code}\s+){old}\b(.*)$", re.M)
        if not pattern.search(text):
            sys.exit(f"Generic.kl has no 'key {code} {old}' line; layout generator needs review")
        # the new name must be one Android already maps somewhere in the original file
        if new not in names:
            sys.exit(f"{new} is not used anywhere in Generic.kl; check the name")
        text = pattern.sub(rf"\g<1>{new}\g<2>", text, count=1)
    header = ("# Pixelbook (EVE) keyboard: top row mapped to the functions printed on the keys.\n"
              "# Generated by input/make_eve_keylayout.py from the image's Generic.kl.\n\n")
    open(dst, "w", encoding="utf-8").write(header + text)
    print(f"wrote {dst}")


if __name__ == "__main__":
    main()
